"""The ONNX embedder must reproduce sentence-transformers' vectors.

Every vector stored by earlier versions was made by sentence-transformers
on PyTorch. If the ONNX embedder drifted from them, new queries would
quietly stop matching old documents, so this compares against reference
vectors generated by sentence-transformers (scripts/make_embedding_fixture.py)
for texts chosen to catch the likely mistakes: truncation at 128 instead of
256 tokens (the repo's tokenizer.json default), pooling over padding, empty
and whitespace-only input, non-ASCII text.

Downloads the pinned ONNX model (~90 MB) on first run; cached afterwards.
"""

import json
import pathlib

import numpy as np
import pytest

from vectorstore.embedding import MODEL_ID, MODEL_REVISION, OnnxEmbedder

REFERENCE = pathlib.Path(__file__).parent / "data" / "embedding_reference.npz"


@pytest.fixture(scope="module")
def embedder():
    return OnnxEmbedder.from_hub()


@pytest.fixture(scope="module")
def reference():
    data = np.load(REFERENCE)
    meta = json.loads(str(data["meta"]))
    return json.loads(str(data["texts"])), data["vectors"], meta


def test_reference_was_made_from_the_pinned_model(reference):
    _, _, meta = reference
    assert (meta["model_id"], meta["model_revision"]) == (MODEL_ID, MODEL_REVISION)
    counts = meta["untruncated_token_counts"]
    # The set must exercise truncation, or the comparison below proves little.
    assert any(128 < c <= 256 for c in counts) and any(c > 256 for c in counts)


def test_matches_sentence_transformers_vectors(embedder, reference):
    texts, expected, _ = reference
    got = embedder.encode(texts)
    cosines = (got * expected).sum(axis=1)
    worst = int(np.argmin(cosines))
    assert cosines.min() > 0.99999, f"text {worst} ({texts[worst][:40]!r}) has cosine {cosines[worst]:.6f}"
    np.testing.assert_allclose(got, expected, atol=1e-4)


def test_result_does_not_depend_on_batch_partners_or_order(embedder, reference):
    texts, _, _ = reference
    together = embedder.encode(texts, batch_size=7)
    one_by_one = np.vstack([embedder.encode([t]) for t in texts])
    reversed_ = embedder.encode(texts[::-1])[::-1]
    np.testing.assert_allclose(together, one_by_one, atol=1e-5)
    np.testing.assert_allclose(together, reversed_, atol=1e-5)


def test_shapes_and_unit_length(embedder):
    assert embedder.get_sentence_embedding_dimension() == 384
    assert embedder.encode([]).shape == (0, 384)
    v = embedder.encode(["a", "b c d"])
    assert v.shape == (2, 384) and v.dtype == np.float32
    np.testing.assert_allclose(np.linalg.norm(v, axis=1), 1.0, atol=1e-5)


def test_semantic_sanity(embedder):
    cat, kitten, rocket = embedder.encode(["a cat sat on the mat", "a kitten sitting on a rug", "rocket engine thrust"])
    assert float(cat @ kitten) > float(cat @ rocket) + 0.2
